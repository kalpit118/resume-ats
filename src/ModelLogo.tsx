import React, { useId } from 'react';

export function getModelCompany(modelId: string): string {
  if (!modelId) return 'default';
  const id = modelId.toLowerCase().trim();
  if (id === 'groq') return 'groq';
  if (id.includes('llama') || id.includes('meta-llama') || id.startsWith('meta/') || id.startsWith('meta-')) return 'meta';
  if (id.includes('mistral') || id.includes('mixtral') || id.includes('codestral') || id.includes('mathstral')) return 'mistral';
  if (id.includes('gemma')) return 'gemma';
  if (id.includes('gemini') || id.includes('google')) return 'gemini';
  if (id.includes('nemotron') || id.includes('nvidia') || id.includes('nv-') || id === 'nim') return 'nvidia';
  if (id.includes('deepseek')) return 'deepseek';
  if (id.includes('qwen') || id.includes('alibaba') || id.includes('qwq')) return 'qwen';
  if (id.includes('phi') || id.includes('microsoft')) return 'microsoft';
  if (id.includes('whisper') || id.includes('gpt') || id.includes('openai') || id.includes('o1') || id.includes('o3')) return 'openai';
  if (id.includes('claude') || id.includes('anthropic')) return 'claude';
  if (id.includes('snowflake') || id.includes('arctic')) return 'snowflake';
  if (id.includes('baichuan')) return 'baichuan';
  if (id.includes('ibm') || id.includes('granite')) return 'ibm';
  if (id.includes('allam')) return 'allam';
  if (id.includes('canopy') || id.includes('orpheus')) return 'canopy';
  return 'default';
}

